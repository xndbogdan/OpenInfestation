use std::fs;
use std::path::{Path, PathBuf};

use thiserror::Error;

const MANAGED_OUTPUT_MARKER: &str = ".inf-extract-managed";

/// Builds one asset family beside its destination and publishes it only after
/// every decoder and serializer succeeds.
pub struct StagedOutput {
    target: PathBuf,
    staging: PathBuf,
    committed: bool,
}

impl StagedOutput {
    pub fn new(target: &Path) -> Result<Self, ManagedOutputError> {
        let name = target
            .file_name()
            .filter(|name| !name.is_empty())
            .ok_or_else(|| ManagedOutputError::InvalidPath(target.to_owned()))?;
        let parent = target
            .parent()
            .filter(|path| !path.as_os_str().is_empty())
            .ok_or_else(|| ManagedOutputError::InvalidPath(target.to_owned()))?;
        create_dir_all(parent)?;
        let nonce = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_err(|_| ManagedOutputError::InvalidPath(target.to_owned()))?
            .as_nanos();
        let staging = parent.join(format!(
            ".{}.inf-extract-staging-{}-{nonce}",
            name.to_string_lossy(),
            std::process::id()
        ));
        create_dir_all(&staging)?;
        Ok(Self {
            target: target.to_owned(),
            staging,
            committed: false,
        })
    }

    pub fn path(&self) -> &Path {
        &self.staging
    }

    pub fn commit(mut self) -> Result<(), ManagedOutputError> {
        write(
            &self.staging.join(MANAGED_OUTPUT_MARKER),
            b"Generated by inf-extract. Safe to replace as one complete asset family.\n",
        )?;
        let backup = if self.target.exists() {
            ensure_managed_output(&self.target)?;
            let backup_path = self.target.with_file_name(format!(
                ".{}.inf-extract-backup-{}",
                self.target.file_name().unwrap().to_string_lossy(),
                std::process::id()
            ));
            if backup_path.exists() {
                return Err(ManagedOutputError::StaleBackup(backup_path));
            }
            Some(backup_path)
        } else {
            None
        };
        let mut operations = RealPublishOperations;
        let cleanup_warning = publish_staging(
            &mut operations,
            &self.staging,
            &self.target,
            backup.as_deref(),
        )?;
        self.committed = true;
        if let Some(warning) = cleanup_warning {
            eprintln!(
                "warning: published {} but could not remove old generated backup {}: {}",
                self.target.display(),
                warning.path.display(),
                warning.source
            );
        }
        Ok(())
    }
}

impl Drop for StagedOutput {
    fn drop(&mut self) {
        if !self.committed && self.staging.exists() {
            let _ = fs::remove_dir_all(&self.staging);
        }
    }
}

#[derive(Debug, Error)]
pub enum ManagedOutputError {
    #[error("invalid managed output path {0}")]
    InvalidPath(PathBuf),

    #[error("refusing to replace unmanaged non-empty output directory {0}")]
    Unmanaged(PathBuf),

    #[error("refusing to replace output while stale backup {0} exists")]
    StaleBackup(PathBuf),

    #[error("failed to create directory {path}: {source}")]
    CreateDirectory {
        path: PathBuf,
        source: std::io::Error,
    },

    #[error("failed to write {path}: {source}")]
    Write {
        path: PathBuf,
        source: std::io::Error,
    },

    #[error("failed to rename {from} to {to}: {source}")]
    Rename {
        from: PathBuf,
        to: PathBuf,
        source: std::io::Error,
    },

    #[error(
        "failed to publish {staging} to {target}: {publish}; restoring {backup} to {target} also failed: {rollback}"
    )]
    PublishRollback {
        staging: PathBuf,
        target: PathBuf,
        backup: PathBuf,
        publish: std::io::Error,
        rollback: std::io::Error,
    },

    #[error("failed to inspect {path}: {source}")]
    Inspect {
        path: PathBuf,
        source: std::io::Error,
    },
}

#[derive(Debug)]
struct CleanupWarning {
    path: PathBuf,
    source: std::io::Error,
}

trait PublishOperations {
    fn rename(&mut self, from: &Path, to: &Path) -> std::io::Result<()>;
    fn remove_dir_all(&mut self, path: &Path) -> std::io::Result<()>;
}

struct RealPublishOperations;

impl PublishOperations for RealPublishOperations {
    fn rename(&mut self, from: &Path, to: &Path) -> std::io::Result<()> {
        rename_with_retry(from, to)
    }

    fn remove_dir_all(&mut self, path: &Path) -> std::io::Result<()> {
        remove_dir_all_with_retry(path)
    }
}

fn publish_staging(
    operations: &mut impl PublishOperations,
    staging: &Path,
    target: &Path,
    backup: Option<&Path>,
) -> Result<Option<CleanupWarning>, ManagedOutputError> {
    if let Some(backup) = backup {
        operations
            .rename(target, backup)
            .map_err(|source| ManagedOutputError::Rename {
                from: target.to_owned(),
                to: backup.to_owned(),
                source,
            })?;
    }

    if let Err(publish) = operations.rename(staging, target) {
        if let Some(backup) = backup {
            if let Err(rollback) = operations.rename(backup, target) {
                return Err(ManagedOutputError::PublishRollback {
                    staging: staging.to_owned(),
                    target: target.to_owned(),
                    backup: backup.to_owned(),
                    publish,
                    rollback,
                });
            }
        }
        return Err(ManagedOutputError::Rename {
            from: staging.to_owned(),
            to: target.to_owned(),
            source: publish,
        });
    }

    let cleanup_warning = backup.and_then(|backup| {
        operations
            .remove_dir_all(backup)
            .err()
            .map(|source| CleanupWarning {
                path: backup.to_owned(),
                source,
            })
    });
    Ok(cleanup_warning)
}

fn ensure_managed_output(path: &Path) -> Result<(), ManagedOutputError> {
    if !path.is_dir() {
        return Err(ManagedOutputError::Unmanaged(path.to_owned()));
    }
    if path.join(MANAGED_OUTPUT_MARKER).is_file() {
        return Ok(());
    }
    let empty = fs::read_dir(path)
        .map_err(|source| ManagedOutputError::Inspect {
            path: path.to_owned(),
            source,
        })?
        .next()
        .is_none();
    if empty {
        Ok(())
    } else {
        Err(ManagedOutputError::Unmanaged(path.to_owned()))
    }
}

fn create_dir_all(path: &Path) -> Result<(), ManagedOutputError> {
    fs::create_dir_all(path).map_err(|source| ManagedOutputError::CreateDirectory {
        path: path.to_owned(),
        source,
    })
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), ManagedOutputError> {
    fs::write(path, bytes).map_err(|source| ManagedOutputError::Write {
        path: path.to_owned(),
        source,
    })
}

fn rename_with_retry(from: &Path, to: &Path) -> std::io::Result<()> {
    const RETRIES: usize = 20;
    for attempt in 0..=RETRIES {
        match fs::rename(from, to) {
            Ok(()) => return Ok(()),
            Err(source)
                if attempt < RETRIES
                    && matches!(
                        source.kind(),
                        std::io::ErrorKind::PermissionDenied | std::io::ErrorKind::WouldBlock
                    ) =>
            {
                // Windows indexing and antivirus can hold a just-written file
                // briefly. The build is already complete in a sibling tree,
                // so a bounded retry preserves atomic publication semantics.
                std::thread::sleep(std::time::Duration::from_millis(50));
            }
            Err(source) => return Err(source),
        }
    }
    unreachable!("rename retry loop always returns")
}

fn remove_dir_all_with_retry(path: &Path) -> std::io::Result<()> {
    const RETRIES: usize = 20;
    for attempt in 0..=RETRIES {
        match fs::remove_dir_all(path) {
            Ok(()) => return Ok(()),
            Err(source)
                if attempt < RETRIES
                    && matches!(
                        source.kind(),
                        std::io::ErrorKind::PermissionDenied | std::io::ErrorKind::WouldBlock
                    ) =>
            {
                std::thread::sleep(std::time::Duration::from_millis(50));
            }
            Err(source) => return Err(source),
        }
    }
    unreachable!("remove retry loop always returns")
}

#[cfg(test)]
mod tests {
    use std::collections::VecDeque;

    use super::*;

    #[derive(Default)]
    struct MockOperations {
        rename_results: VecDeque<Option<std::io::ErrorKind>>,
        remove_result: Option<std::io::ErrorKind>,
        calls: Vec<String>,
    }

    impl PublishOperations for MockOperations {
        fn rename(&mut self, from: &Path, to: &Path) -> std::io::Result<()> {
            self.calls
                .push(format!("rename:{}->{}", from.display(), to.display()));
            match self.rename_results.pop_front().flatten() {
                Some(kind) => Err(std::io::Error::from(kind)),
                None => Ok(()),
            }
        }

        fn remove_dir_all(&mut self, path: &Path) -> std::io::Result<()> {
            self.calls.push(format!("remove:{}", path.display()));
            match self.remove_result.take() {
                Some(kind) => Err(std::io::Error::from(kind)),
                None => Ok(()),
            }
        }
    }

    #[test]
    fn failed_publish_restores_the_previous_target() {
        let mut operations = MockOperations {
            rename_results: [None, Some(std::io::ErrorKind::PermissionDenied), None].into(),
            ..MockOperations::default()
        };
        let error = publish_staging(
            &mut operations,
            Path::new("staging"),
            Path::new("target"),
            Some(Path::new("backup")),
        )
        .unwrap_err();

        assert!(matches!(
            error,
            ManagedOutputError::Rename { ref from, ref to, .. }
                if from == Path::new("staging") && to == Path::new("target")
        ));
        assert_eq!(
            operations.calls,
            [
                "rename:target->backup",
                "rename:staging->target",
                "rename:backup->target",
            ]
        );
    }

    #[test]
    fn failed_publish_surfaces_a_failed_rollback() {
        let mut operations = MockOperations {
            rename_results: [
                None,
                Some(std::io::ErrorKind::PermissionDenied),
                Some(std::io::ErrorKind::Other),
            ]
            .into(),
            ..MockOperations::default()
        };
        let error = publish_staging(
            &mut operations,
            Path::new("staging"),
            Path::new("target"),
            Some(Path::new("backup")),
        )
        .unwrap_err();

        assert!(matches!(
            error,
            ManagedOutputError::PublishRollback {
                ref staging,
                ref target,
                ref backup,
                ..
            } if staging == Path::new("staging")
                && target == Path::new("target")
                && backup == Path::new("backup")
        ));
    }

    #[test]
    fn backup_cleanup_failure_does_not_relabel_a_published_target_as_failed() {
        let mut operations = MockOperations {
            rename_results: [None, None].into(),
            remove_result: Some(std::io::ErrorKind::PermissionDenied),
            ..MockOperations::default()
        };
        let warning = publish_staging(
            &mut operations,
            Path::new("staging"),
            Path::new("target"),
            Some(Path::new("backup")),
        )
        .unwrap()
        .expect("cleanup failure must be reported as a non-fatal warning");

        assert_eq!(warning.path, Path::new("backup"));
        assert_eq!(warning.source.kind(), std::io::ErrorKind::PermissionDenied);
        assert_eq!(
            operations.calls,
            [
                "rename:target->backup",
                "rename:staging->target",
                "remove:backup",
            ]
        );
    }

    #[test]
    fn real_publication_replaces_only_managed_targets() {
        let root = std::env::temp_dir().join(format!(
            "infestation-managed-output-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let target = root.join("family");

        let first = StagedOutput::new(&target).unwrap();
        fs::write(first.path().join("value.txt"), b"first").unwrap();
        first.commit().unwrap();
        assert_eq!(fs::read(target.join("value.txt")).unwrap(), b"first");
        assert!(target.join(MANAGED_OUTPUT_MARKER).is_file());

        let second = StagedOutput::new(&target).unwrap();
        fs::write(second.path().join("value.txt"), b"second").unwrap();
        second.commit().unwrap();
        assert_eq!(fs::read(target.join("value.txt")).unwrap(), b"second");
        assert!(target.join(MANAGED_OUTPUT_MARKER).is_file());

        fs::remove_dir_all(root).unwrap();
    }
}
