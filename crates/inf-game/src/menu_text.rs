//! Authored label callbacks 004834F0/00453A80 and text 00453810,
//! 004A3B20/004A3E30, single-line 004A3AB0/004A3BA0 and measure 004A4240.
//! Layout is concrete; actual sprite submission remains a required backend
//! operation. No glyph pixels or UVs are invented.

use inf_formats::{Font, FontMode, GlyphMetrics};
use thiserror::Error;

use crate::menu::{MenuColor, MenuRowDescriptor, MenuRowDrawRequest};

/// 004A3A70 initializes the three RGB bytes; the high byte is zero-initialized.
pub const INITIAL_GLYPH_BASE_WORD: u32 = 0x0080_8080;
const REVEAL_TABLE_ADDRESS: i32 = 0x0054_15c8;
const REVEAL_MULTIPLIERS: [u8; 17] = [
    128, 132, 138, 146, 156, 168, 178, 186, 194, 202, 210, 216, 220, 222, 220, 176, 132,
];
const REVEAL_STEP_MILLIS: i32 = 25; // DWORD 005415DC

pub trait MenuTextResources {
    type Error;
    fn string(&self, argument: i32) -> Result<&[u8], Self::Error>;
    fn font(&self, argument: i32) -> Result<&Font, Self::Error>;
    fn style(&self, argument: i32) -> Result<u32, Self::Error>;
    /// Logical H3 entry +14/+16: FIRST physical variant dimensions, before
    /// render-mode selection. The full callback argument must be retained.
    fn sprite_dimensions(&self, argument: i32) -> Result<[u16; 2], Self::Error>;
}

/// The actual descriptor +20 values used by the two virtual+A4 calls.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum MenuGlyphPass {
    Base = 1,
    Color = 0,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct MenuGlyphQuad {
    pub sprite_argument: i32,
    /// Top-left, top-right, bottom-right, bottom-left, in native signed WORD
    /// coordinates. Each vertex carries the native DWORD attribute 0x40.
    pub corners: [[i16; 2]; 4],
    pub context_origin_pixels: [i32; 2],
    pub pass: MenuGlyphPass,
    /// Descriptor +28. Descriptor +24 is the resolved sprite resource.
    pub color: MenuColor,
}

pub trait MenuTextHost {
    type Error;
    /// Execute one virtual+A4 submission. A failure preserves earlier glyph
    /// submissions; there is no recording/default success implementation.
    fn submit_glyph(&mut self, glyph: MenuGlyphQuad) -> Result<(), Self::Error>;
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct MenuTextOutcome {
    /// Native descriptor +18, final returned X minus original descriptor X.
    pub advance_from_origin: i32,
}

/// Which non-NULL text argument is supplied to 00453810. Right text uses
/// the native 500 ms reveal delay and does not write back row Y.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MenuTextPlacement {
    Left,
    Right,
}

/// A single left or right string at 00453810, including generated bytes.
/// Font 0 and optional shadow style 7 are resolved by the consumer.
pub struct MenuRowTextRequest<'a> {
    pub descriptor: &'a mut MenuRowDescriptor,
    pub text: &'a [u8],
    pub placement: MenuTextPlacement,
    pub context_origin_pixels: [i32; 2],
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MenuTextEmission {
    Draw,
    /// Native NULL glyph callback: layout still executes, including grid
    /// selection and word lookahead, without resolving sprite dimensions.
    Measure,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MenuTextReveal {
    Complete,
    /// Raw descriptor bit 1 and +24. No row-specific delay is applied here.
    Timed {
        age_millis: i32,
    },
}

/// Positioned 004A3B20 text. The caller supplies the actual resolved font and
/// base color (raw descriptor bit 0/+20 or the native shared glyph base).
/// It adds neither a shadow nor alignment nor the context origin to pixels.
pub struct RawMenuTextRequest<'a> {
    pub text: &'a [u8],
    pub font: &'a Font,
    pub position_pixels: [i32; 2],
    pub width_pixels: i32,
    pub color: MenuColor,
    pub base_color: MenuColor,
    pub context_origin_pixels: [i32; 2],
    pub emission: MenuTextEmission,
    pub reveal: MenuTextReveal,
}

/// Positioned 004A3AB0 single-line text. The caller supplies the resolved font
/// and base color (descriptor bit 0/+20, else the shared word 0055F8F8, which
/// 004A3BA0 writes only into its private descriptor copy). There is no wrap,
/// width, reveal or NULL-text substitution, and the glyph callback is always
/// present at its callers.
pub struct LineTextRequest<'a> {
    pub text: &'a [u8],
    pub font: &'a Font,
    pub position_pixels: [i32; 2],
    pub color: MenuColor,
    pub base_color: MenuColor,
    pub context_origin_pixels: [i32; 2],
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum MenuTextLayoutError {
    #[error("font metric for byte {0} is outside the decoded table")]
    Metric(u8),
    #[error("font sprite index {0} is outside the decoded table")]
    Sprite(i32),
    #[error("native signed text division {numerator}/{divisor} faults")]
    Division { numerator: i32, divisor: i32 },
    #[error("font fallback remaps the terminal NUL during word lookahead")]
    PastTerminator,
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum MenuTextError<R, H> {
    #[error("row callback {0:08X} is outside the recovered label families")]
    UnsupportedCallback(u32),
    #[error("text resource: {0}")]
    Resource(R),
    #[error("text backend: {0}")]
    Backend(H),
    #[error(transparent)]
    Layout(#[from] MenuTextLayoutError),
}

/// Dispatch after frontend camera wrappers have selected the actual callback.
/// Root 004834F0 draws right-aligned; generic 00453A80 draws left-aligned.
pub fn draw_menu_text_row<R: MenuTextResources, H: MenuTextHost>(
    request: &mut MenuRowDrawRequest,
    resources: &R,
    host: &mut H,
) -> Result<MenuTextOutcome, MenuTextError<R::Error, H::Error>> {
    let placement = match request.callback_address {
        0x0048_34f0 => MenuTextPlacement::Right,
        0x0045_3a80 => MenuTextPlacement::Left,
        other => return Err(MenuTextError::UnsupportedCallback(other)),
    };
    // Wrapper resolves the full string argument before 00453810 resolves font0.
    let text = resources
        .string(request.arguments[0] as i32)
        .map_err(MenuTextError::Resource)?;
    draw_row_text(
        MenuRowTextRequest {
            descriptor: &mut request.descriptor,
            text,
            placement,
            context_origin_pixels: request.context_origin_pixels,
        },
        resources,
        host,
    )
}

/// Execute the one-sided 00453810 row consumer without an H0 lookup. The
/// row's native early-Y write remains visible when a later submission fails;
/// +18 advance is returned only after the complete call succeeds.
pub fn draw_row_text<R: MenuTextResources, H: MenuTextHost>(
    request: MenuRowTextRequest<'_>,
    resources: &R,
    host: &mut H,
) -> Result<MenuTextOutcome, MenuTextError<R::Error, H::Error>> {
    let right = request.placement == MenuTextPlacement::Right;
    let text = request.text;
    let font = resources.font(0).map_err(MenuTextError::Resource)?;
    let original = *request.descriptor;
    let origin = original.position_pixels.map(i32::from);
    let mut start = origin;
    let animated = original.reveal != u16::MAX;
    let reveal = if animated && original.flags & 0x20 == 0 {
        Some(
            original
                .age_millis
                .wrapping_sub(if right { 500 } else { 0 }),
        )
    } else {
        None
    };
    let mut context = TextContext {
        font,
        resources,
        host,
        context_origin_pixels: request.context_origin_pixels,
    };
    let mut input = TextInput {
        text,
        start,
        width: i32::from(original.extent_pixels[0]),
        reveal,
        emit: original.flags & 8 == 0,
        color: original.color,
        base_color: MenuColor::from_word(INITIAL_GLYPH_BASE_WORD),
    };
    if animated && !right {
        let measured = context.walk(TextInput {
            emit: false,
            ..input
        })?;
        request.descriptor.position_pixels[1] = measured[1] as i16;
        if original.flags & 2 != 0 {
            start[0] = start[0].wrapping_sub(i32::from(measure_text_width(font, text)? as i16) / 2);
        }
    }
    if right {
        start[0] = start[0]
            .wrapping_add(i32::from(original.extent_pixels[0]))
            .wrapping_sub(i32::from(measure_text_width(font, text)? as i16));
    }
    input.start = start;
    if original.flags & 0x40 == 0 {
        let shadow = resources.style(7).map_err(MenuTextError::Resource)?;
        context.walk(TextInput {
            start: start.map(|v| v.wrapping_add(1)),
            color: MenuColor::from_word(shadow),
            ..input
        })?;
    }
    let end = context.walk(input)?;
    if !animated && !right {
        request.descriptor.position_pixels[1] = end[1] as i16;
    }
    Ok(MenuTextOutcome {
        advance_from_origin: end[0].wrapping_sub(origin[0]),
    })
}

/// Execute raw positioned text and publish its narrowed X/Y on return.
/// Glyph failures retain prior submissions and leave position unchanged.
/// As in 004A3B8C, a final Y-division fault can occur after X is published.
pub fn draw_raw_text<R: MenuTextResources, H: MenuTextHost>(
    request: &mut RawMenuTextRequest<'_>,
    resources: &R,
    host: &mut H,
) -> Result<(), MenuTextError<R::Error, H::Error>> {
    let mut context = TextContext {
        font: request.font,
        resources,
        host,
        context_origin_pixels: request.context_origin_pixels,
    };
    let position = context.walk_units(TextInput {
        text: request.text,
        start: request.position_pixels,
        width: request.width_pixels,
        reveal: match request.reveal {
            MenuTextReveal::Complete => None,
            MenuTextReveal::Timed { age_millis } => Some(age_millis),
        },
        emit: request.emission == MenuTextEmission::Draw,
        color: request.color,
        base_color: request.base_color,
    })?;
    for (output, value) in request.position_pixels.iter_mut().zip(position) {
        *output = i32::from(divide(value, request.font.coordinate_divisor)? as i16);
    }
    Ok(())
}

/// Execute 004A3AB0 and publish its narrowed X/Y on return. Every consumed
/// byte advances by its metric advance plus spacing; spaces and hyphens are
/// ordinary glyphs. Glyph failures retain prior submissions and leave the
/// position unchanged; as in 004A3AF4..004A3B0B, a final Y-division fault can
/// occur after X is published.
pub fn draw_line_text<R: MenuTextResources, H: MenuTextHost>(
    request: &mut LineTextRequest<'_>,
    resources: &R,
    host: &mut H,
) -> Result<(), MenuTextError<R::Error, H::Error>> {
    let mut context = TextContext {
        font: request.font,
        resources,
        host,
        context_origin_pixels: request.context_origin_pixels,
    };
    let position = context.walk_line(
        request.text,
        request.position_pixels,
        request.color,
        request.base_color,
    )?;
    for (output, value) in request.position_pixels.iter_mut().zip(position) {
        *output = i32::from(divide(value, request.font.coordinate_divisor)? as i16);
    }
    Ok(())
}

/// 004A4240 measures original bytes without fallback or newline mapping and
/// omits spacing after the final byte. Row callers subsequently narrow to AX.
pub fn measure_text_width(font: &Font, text: &[u8]) -> Result<i32, MenuTextLayoutError> {
    let text = terminated(text);
    let mut width = 0i32;
    for (index, &byte) in text.iter().enumerate() {
        let metric = metric(font, byte)?;
        width = width.wrapping_add(i32::from(metric.advance));
        if index + 1 != text.len() {
            width = width.wrapping_add(i32::from(metric.spacing));
        }
    }
    divide(width, font.coordinate_divisor)
}

#[derive(Clone, Copy)]
struct TextInput<'a> {
    text: &'a [u8],
    start: [i32; 2],
    width: i32,
    reveal: Option<i32>,
    emit: bool,
    color: MenuColor,
    base_color: MenuColor,
}

struct TextContext<'a, R, H> {
    font: &'a Font,
    resources: &'a R,
    host: &'a mut H,
    context_origin_pixels: [i32; 2],
}

impl<R: MenuTextResources, H: MenuTextHost> TextContext<'_, R, H> {
    fn walk(
        &mut self,
        input: TextInput<'_>,
    ) -> Result<[i32; 2], MenuTextError<R::Error, H::Error>> {
        let position = self.walk_units(input)?;
        Ok([
            i32::from(divide(position[0], self.font.coordinate_divisor)? as i16),
            i32::from(divide(position[1], self.font.coordinate_divisor)? as i16),
        ])
    }

    fn walk_units(
        &mut self,
        input: TextInput<'_>,
    ) -> Result<[i32; 2], MenuTextError<R::Error, H::Error>> {
        let divisor = self.font.coordinate_divisor;
        let text = terminated(input.text);
        let start = input.start.map(|v| v.wrapping_mul(divisor));
        let limit = start[0].wrapping_add(input.width.wrapping_mul(divisor));
        let mut position = start;
        let mut cursor = 0usize;
        let mut saved_cursor = 0usize;
        let mut saved_x = start[0];
        let mut drawing = true;
        // Reproduce signed comparisons of the original virtual pointer, including
        // overflow; a huge time is not a saturating reveal-character count.
        let mut reveal_pointer = (REVEAL_TABLE_ADDRESS + 17)
            .wrapping_sub(input.reveal.unwrap_or(0) / REVEAL_STEP_MILLIS);
        loop {
            let source_byte = if cursor == text.len() {
                0
            } else {
                *text
                    .get(cursor)
                    .ok_or(MenuTextLayoutError::PastTerminator)?
            };
            cursor += 1;
            if source_byte == 0 && drawing {
                break;
            }
            let mut byte = if i32::from(source_byte) > self.font.maximum_byte {
                b'!'
            } else {
                source_byte
            };
            if sprite(self.font, i32::from(byte))? == 0 {
                byte = self.font.fallback_byte;
            }
            let metric = metric(self.font, byte)?;
            let mut color = input.color;
            let mut skip = false;
            if drawing && input.reveal.is_some() {
                if reveal_pointer >= REVEAL_TABLE_ADDRESS + 17 {
                    skip = true;
                } else if reveal_pointer >= REVEAL_TABLE_ADDRESS {
                    color = modulate(
                        color,
                        REVEAL_MULTIPLIERS[(reveal_pointer - REVEAL_TABLE_ADDRESS) as usize],
                    );
                }
                reveal_pointer = reveal_pointer.wrapping_add(1);
            }
            // Native computes mode-specific coordinates/table selection even
            // during lookahead and when the glyph callback is disabled.
            let (sprite_argument, glyph_position) =
                glyph_position(self.font, byte, metric, position)?;
            if drawing && !skip && input.emit {
                self.submit_glyph_pair(sprite_argument, glyph_position, color, input.base_color)?;
            }
            position[0] = position[0]
                .wrapping_add(i32::from(metric.advance))
                .wrapping_add(i32::from(metric.spacing));
            if matches!(byte, b' ' | b'-' | 0) {
                if drawing {
                    saved_cursor = cursor;
                    saved_x = position[0];
                    drawing = false;
                } else {
                    let before = position[0]
                        .wrapping_sub(i32::from(metric.advance))
                        .wrapping_sub(i32::from(metric.spacing));
                    if limit < before {
                        position[1] = position[1]
                            .wrapping_add(self.font.line_step_terms[1])
                            .wrapping_add(self.font.line_step_terms[0]);
                        saved_x = start[0];
                    }
                    drawing = true;
                    cursor = saved_cursor;
                    position[0] = saved_x;
                }
            }
        }
        Ok(position)
    }

    /// 004A3BA0: one pass over the terminated bytes in font units, starting
    /// at the scaled pixel position. Y never changes.
    fn walk_line(
        &mut self,
        text: &[u8],
        start: [i32; 2],
        color: MenuColor,
        base_color: MenuColor,
    ) -> Result<[i32; 2], MenuTextError<R::Error, H::Error>> {
        let divisor = self.font.coordinate_divisor;
        let mut position = start.map(|v| v.wrapping_mul(divisor));
        for &source_byte in terminated(text) {
            let mut byte = if i32::from(source_byte) > self.font.maximum_byte {
                b'!'
            } else {
                source_byte
            };
            if sprite(self.font, i32::from(byte))? == 0 {
                byte = self.font.fallback_byte;
            }
            let metric = metric(self.font, byte)?;
            let (sprite_argument, glyph_position) =
                glyph_position(self.font, byte, metric, position)?;
            self.submit_glyph_pair(sprite_argument, glyph_position, color, base_color)?;
            position[0] = position[0]
                .wrapping_add(i32::from(metric.advance))
                .wrapping_add(i32::from(metric.spacing));
        }
        Ok(position)
    }

    /// The glyph callback's sprite dimensions, then the base pass and the
    /// color pass through virtual+A4 (004A3D2B..004A3DC9).
    fn submit_glyph_pair(
        &mut self,
        sprite_argument: u32,
        glyph_position: [i32; 2],
        color: MenuColor,
        base_color: MenuColor,
    ) -> Result<(), MenuTextError<R::Error, H::Error>> {
        let [width, height] = self
            .resources
            .sprite_dimensions(sprite_argument as i32)
            .map_err(MenuTextError::Resource)?;
        let left = glyph_position[0] as i16;
        let right = glyph_position[0].wrapping_add(i32::from(width >> 2)) as i16;
        let bottom = glyph_position[1] as i16;
        let top = glyph_position[1].wrapping_sub((i32::from(height) + 2) / 4) as i16;
        let glyph = MenuGlyphQuad {
            sprite_argument: sprite_argument as i32,
            corners: [[left, top], [right, top], [right, bottom], [left, bottom]],
            context_origin_pixels: self.context_origin_pixels,
            pass: MenuGlyphPass::Base,
            color: base_color,
        };
        self.host
            .submit_glyph(glyph)
            .map_err(MenuTextError::Backend)?;
        self.host
            .submit_glyph(MenuGlyphQuad {
                pass: MenuGlyphPass::Color,
                color,
                ..glyph
            })
            .map_err(MenuTextError::Backend)
    }
}

fn glyph_position(
    font: &Font,
    byte: u8,
    metric: GlyphMetrics,
    position: [i32; 2],
) -> Result<(u32, [i32; 2]), MenuTextLayoutError> {
    let divisor = font.coordinate_divisor;
    let offset = metric.offset.map(|v| i32::from(v) * 100);
    match font.mode {
        FontMode::Direct => Ok((
            sprite(font, i32::from(byte))?,
            [
                divide(position[0].wrapping_add(offset[0]), divisor)?,
                divide(position[1].wrapping_add(offset[1]), divisor)?,
            ],
        )),
        FontMode::PositionGrid { columns, rows } => {
            let pixel = [divide(position[0], divisor)?, divide(position[1], divisor)?];
            let phase = divide(rows.wrapping_mul(position[1]), divisor)?
                .wrapping_sub(rows.wrapping_mul(pixel[1]))
                .wrapping_sub(pixel[0])
                .wrapping_mul(columns)
                .wrapping_add(divide(columns.wrapping_mul(position[0]), divisor)?);
            let index = phase
                .wrapping_mul(font.metrics.len() as i32)
                .wrapping_add(i32::from(byte));
            Ok((
                sprite(font, index)?,
                [
                    pixel[0].wrapping_add(divide(offset[0], divisor)?),
                    pixel[1].wrapping_add(divide(offset[1], divisor)?),
                ],
            ))
        }
    }
}

fn modulate(color: MenuColor, multiplier: u8) -> MenuColor {
    MenuColor {
        rgb: color
            .rgb
            .map(|v| ((u32::from(v) * u32::from(multiplier)) >> 7).min(255) as u8),
        ..color
    }
}

fn terminated(text: &[u8]) -> &[u8] {
    &text[..text.iter().position(|&v| v == 0).unwrap_or(text.len())]
}
fn metric(font: &Font, byte: u8) -> Result<GlyphMetrics, MenuTextLayoutError> {
    font.metrics
        .get(usize::from(byte))
        .copied()
        .ok_or(MenuTextLayoutError::Metric(byte))
}
fn sprite(font: &Font, index: i32) -> Result<u32, MenuTextLayoutError> {
    usize::try_from(index)
        .ok()
        .and_then(|i| font.sprite_words.get(i))
        .copied()
        .ok_or(MenuTextLayoutError::Sprite(index))
}
fn divide(numerator: i32, divisor: i32) -> Result<i32, MenuTextLayoutError> {
    numerator
        .checked_div(divisor)
        .ok_or(MenuTextLayoutError::Division { numerator, divisor })
}

