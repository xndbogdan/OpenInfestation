#[test]
fn mapped_policies_static_sentinel_table_and_loader_zero_domains_match_original() {
    let bytes = original();
    let executable = inf_formats::FrontendExecutable::parse(&bytes).unwrap();
    for (address, length, expected) in [
        (
            0x0053AA38_u32,
            4_usize,
            "0d2b48ab57c78a609ad955ee6907d54b8e13adc460ca8e651af38c206f4e81c1",
        ),
        (
            0x00527700_u32,
            20_usize,
            "2b26ed089ef5c5f334b5bf3cf21165a7f962cdd6358492605433c8280b1b1ebf",
        ),
        (
            0x00527DA8_u32,
            8_usize,
            "0e0aeb4322037b6232598f344660322892b53108c12370c305e0e4bdb3d71dec",
        ),
        (
            0x00527EE0_u32,
            64_usize,
            "a4e503a32c8d4e188c045ba52c46202495a4efcb3302e77a8af8f8e10f6f921f",
        ),
        (
            0x0053BB80_u32,
            8_usize,
            "b244d7aac9a1e647b28bb5abd094c8e8e9d67da041f3f569f7cffd49f94bd6f0",
        ),
        (
            0x00527FE0_u32,
            28_usize,
            "fd07f18aaf59905763a6e0a8f660beacaaa3926bf597662fb17a7ddcc8a350b0",
        ),
    ] {
        assert_eq!(
            format!(
                "{:x}",
                Sha256::digest(executable.mapped(address, length).unwrap().bytes)
            ),
            expected
        );
    }
    //Loader zeros prove process startup only; static47FEF0 then installs
    //head55F0E8 and terminator55F0EC without allocating any40-byte sentinel.
    executable.loader_zero_data(0x0055F0E8, 16).unwrap();
    executable.loader_zero_data(0x0065F248, 1).unwrap();
    executable.loader_zero_data(0x0065ECB8, 16).unwrap();
    let table = executable.mapped(0x00527ee0, 64).unwrap().bytes;
    assert_eq!(
        u32::from_le_bytes(table[0x24..0x28].try_into().unwrap()),
        0x00481710
    );
    assert_eq!(
        u32::from_le_bytes(table[0x3c..0x40].try_into().unwrap()),
        0x0047ebf0
    );
    //Actual alternate+3C is47EBF0, not481A50; no callback substitution.
}

